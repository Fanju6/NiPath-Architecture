test('Android: preserve tab filters and route history while navigating', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'android-phone')
  await page.goto('/')
  const nav=page.getByRole('navigation',{name:'底部主导航'})
  await nav.getByRole('button',{name:'资源'}).click()
  await page.getByRole('tab',{name:/节点/}).click()
  await expect(page.getByRole('tab',{name:/节点/})).toHaveAttribute('aria-selected','true')
  await nav.getByRole('button',{name:'规则'}).click()
  await nav.getByRole('button',{name:'资源'}).click()
  await expect(page.getByRole('tab',{name:/节点/})).toHaveAttribute('aria-selected','true')
  await page.goBack()
  await expect(nav.getByRole('button',{name:'规则'})).toHaveAttribute('aria-current','page')
  await page.goBack()
  await expect(nav.getByRole('button',{name:'资源'})).toHaveAttribute('aria-current','page')

  await page.getByRole('button',{name:'添加订阅'}).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(nav.getByRole('button',{name:'资源'})).toHaveAttribute('aria-current','page')

  await nav.getByRole('button',{name:'代理'}).click()
  await page.getByRole('button',{name:'添加策略组'}).click()
  const dialog=page.getByRole('dialog')
  await dialog.locator('input').first().fill('回退测试组')
  await dialog.locator('textarea').fill('direct')
  await dialog.getByRole('button',{name:'确认添加'}).click()
  await page.getByRole('button',{name:/回退测试组/}).click()
  await expect(page.getByTestId('mobile-detail-title')).toHaveText('回退测试组')
  await page.goBack()
  await expect(nav).toBeVisible()
  await expect(page.getByRole('button',{name:/回退测试组/})).toBeVisible()
})

